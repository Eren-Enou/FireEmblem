"""Install codes/GFEE01.ini into the portable Dolphin user folder.

Copies the [ActionReplay] / [Gecko] definitions into Dolphin-x64/User/GameSettings/GFEE01.ini
and enables only the codes named with --enable (none by default). An existing user ini is
backed up to GFEE01.ini.bak first. Never touches the game image.

Usage: python -m tools.install_codes [--enable EXP-01] [--dolphin Dolphin-x64]
       python -m tools.install_codes --enable EXP-01      (matches the code id token)
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def parse_sections(text: str) -> dict[str, list[str]]:
    sections: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        if s.startswith("[") and s.endswith("]"):
            current = s[1:-1]
            sections.setdefault(current, [])
        elif current:
            sections[current].append(s)
    return sections


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dolphin", type=Path, default=ROOT / "Dolphin-x64")
    ap.add_argument("--enable", action="append", default=[], help="code name prefix to enable")
    args = ap.parse_args()

    src = parse_sections((ROOT / "codes/GFEE01.ini").read_text())
    out_lines = ["# Generated by tools/install_codes.py from codes/GFEE01.ini -- edit that file instead."]
    for kind in ("ActionReplay", "Gecko"):
        lines = src.get(kind, [])
        if not lines:
            continue
        names = [l[1:] for l in lines if l.startswith("$")]
        # match on the id token ("EXP-01") so EXP-01 does not also select EXP-010 etc.
        enabled = [n for n in names if any(n == p or n.startswith(p + " ") for p in args.enable)]
        out_lines += [f"[{kind}]", *lines, f"[{kind}_Enabled]", *[f"${n}" for n in enabled]]
        for n in enabled:
            print(f"enabled: {n}")

    dest = args.dolphin / "User/GameSettings/GFEE01.ini"
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists():
        shutil.copy2(dest, dest.with_suffix(".ini.bak"))
        print(f"backed up existing {dest.name}")
    dest.write_text("\n".join(out_lines) + "\n")
    print(f"wrote {dest}")
    print("Remember: Dolphin > Config > General > 'Enable Cheats' must be on.")


if __name__ == "__main__":
    main()
